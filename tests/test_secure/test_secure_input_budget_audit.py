@pytest.mark.parametrize("operation", ["lock", "close", "rotate"])
def test_store_releases_unreferenced_fernet_after_lifecycle_transition(
    tmp_path: Path,
    operation: str,
) -> None:
    store = SecureStore(base_dir=tmp_path)
    try:
        store.unlock()
        owned = store.fernet
        assert owned is not None
        reference = weakref.ref(owned)
        del owned
        if operation == "rotate":
            store.rotate_master_key()
        else:
            getattr(store, operation)()
        gc.collect()  # noqa: GS020
        assert reference() is None
    finally:
        store.close()


def _snapshot(
    base: Path,
) -> tuple[dict[str, bytes], list[tuple[object, ...]]]:
    with closing(sqlite3.connect(base / "config.db")) as connection:
        return (
            dict(connection.execute("SELECT key, value FROM store_meta ORDER BY key")),
            list(
                connection.execute(
                    "SELECT name, ciphertext, acl FROM secrets ORDER BY name"
                )
            ),
        )


@pytest.mark.parametrize("passphrase", [None, "synthetic-existing-passphrase"])
def test_missing_primary_never_creates_unrelated_material_for_existing_database(
    tmp_path: Path,
    passphrase: str | None,
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock(passphrase)
        store.set("secret", "synthetic-value")
    before = _snapshot(tmp_path)
    primary = tmp_path / ("master.key" if passphrase is None else "master.salt")
    primary.unlink()  #? Missing material in this synthetic fixture, not a live store.
    with SecureStore(base_dir=tmp_path) as rejected:
        with pytest.raises((InvalidToken, RuntimeError)):
            rejected.unlock(passphrase)
        assert not rejected.is_unlocked()
    assert _snapshot(tmp_path) == before
    assert not primary.exists(), (
        "rejected unlock must not publish an unrelated new key/salt"
    )


def test_malformed_primary_does_not_block_verified_pending_rotation_recovery(
    tmp_path: Path,
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock()
        store.set("secret", "synthetic-value")
        with patch.object(
            store,
            "_promote_pending_key_material",
            side_effect=OSError("synthetic pause"),
        ):
            with pytest.raises(OSError, match="synthetic pause"):
                store.rotate_master_key()
        store._master_key_path.write_bytes(b"malformed-key")
    pending = tmp_path / ".master.key.pending"
    check = dict(_snapshot(tmp_path)[0])["key_check"]
    assert isinstance(check, bytes)
    assert (
        Fernet(pending.read_bytes()).decrypt(check)
        == b"gunz-utils-secure-store-v2:strict"
    )
    with SecureStore(base_dir=tmp_path) as recovered:
        recovered.unlock()
        assert recovered.verify_integrity()
        assert recovered.get("secret") == "synthetic-value"
        assert not pending.exists()


def test_unsigned_generation_reset_cannot_authorize_obsolete_key_new_writes(
    tmp_path: Path,
) -> None:
    with (
        SecureStore(base_dir=tmp_path) as current,
        SecureStore(base_dir=tmp_path) as stale,
    ):
        current.unlock("synthetic-old-passphrase")
        stale.unlock("synthetic-old-passphrase")
        current.rotate_master_key("synthetic-new-passphrase")
        marker = dict(_snapshot(tmp_path)[0])["key_check"]
        current._conn.execute(
            "UPDATE store_meta SET value=? WHERE key='key_generation'", (b"1",)
        )
        #? Only this unsigned counter changes; the authenticated current marker
        #? is neither forged nor replayed from an older snapshot.
        with pytest.raises((RuntimeError, InvalidToken)):
            stale.set("future", "synthetic-future-secret")
        assert dict(_snapshot(tmp_path)[0])["key_check"] == marker
        assert not current._conn.execute(
            "SELECT name FROM secrets WHERE name='future'"
        ).fetchone()
        assert current._conn.execute(
            "SELECT COUNT(*) FROM audit WHERE action='set' AND allowed=1 "
            "AND secret_name='future'"
        ).fetchone()[0] == 0


