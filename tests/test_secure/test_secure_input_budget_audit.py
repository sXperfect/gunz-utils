@pytest.mark.parametrize(
    "plaintext,ciphertext,tag",
    [
        ("", "", "530f8afbc74536b9a963b4f1c4cb738b"),
        (
            "\0" * 16,
            "cea7403d4d606b6e074ec5d3baf39d18",
            "d0d1c8a799996bf0265b98b5d48ab919",
        ),
    ],
)
def test_aes256_gcm_wire_matches_independent_openssl_vectors(
    plaintext: str,
    ciphertext: str,
    tag: str,
) -> None:
    #? Published upstream vectors, not output generated by the implementation:
    #? openssl/openssl test/recipes/30-test_evp_data/evpciph_aes_common.txt.
    expected = f"aes256:v2:{'00' * 16}:{'00' * 12}:{tag}:{ciphertext}"
    with (
        patch.object(secure_crypto.os, "urandom", side_effect=lambda size: bytes(size)),
        patch.object(secure_crypto, "get_derived_key", return_value=bytes(32)),
    ):
        assert (
            secure_crypto.encrypt(plaintext, "synthetic-vector-passphrase") == expected
        )
        assert (
            secure_crypto.decrypt(expected, "synthetic-vector-passphrase") == plaintext
        )


def test_pbkdf2_key_derivation_matches_standard_library_oracle() -> None:
    salt = bytes(range(16))
    passphrase = "synthetic-π-passphrase"
    expected = hashlib.pbkdf2_hmac(
        "sha256", passphrase.encode("utf-8"), salt, 600_000, dklen=32
    )
    assert secure_crypto.get_derived_key(salt, passphrase) == expected


