@pytest.mark.parametrize(
    "component", [0, 1, 2, 3], ids=["salt", "iv", "tag", "ciphertext"]
)
def test_each_wire_component_tamper_fails_authentication(
    authenticated_wire: str,
    component: int,
) -> None:
    parts = authenticated_wire.removeprefix("aes256:v2:").split(":")
    changed = bytearray.fromhex(parts[component])
    changed[0] ^= 1
    parts[component] = changed.hex()
    with pytest.raises(InvalidTag) as error:
        secure_crypto.decrypt(
            "aes256:v2:" + ":".join(parts), "synthetic-component-passphrase"
        )
    assert "synthetic-component-value" not in str(error.value)
    assert "synthetic-component-passphrase" not in str(error.value)


