@pytest.mark.parametrize("operation", ["lock", "close", "rotate"])
def test_store_releases_unreferenced_fernet_after_lifecycle_transition(
    tmp_path: Path, operation: str
) -> None:
    store = SecureStore(base_dir=tmp_path)
    try:
        store.unlock()
        owned = store.fernet
        assert owned is not None
        reference = weakref.ref(owned)
        del owned
        if operation == "rotate":
            store.rotate_master_key()
        else:
            getattr(store, operation)()
        gc.collect()
        assert reference() is None
    finally:
        store.close()


def _snapshot(base: Path) -> tuple[dict[str, bytes], list[tuple[object, ...]]]:
    with closing(sqlite3.connect(base / "config.db")) as connection:
        return (
            dict(connection.execute("SELECT key, value FROM store_meta ORDER BY key")),
            list(
                connection.execute(
                    "SELECT name, ciphertext, acl FROM secrets ORDER BY name"
                )
            ),
        )


@pytest.mark.parametrize("passphrase", [None, "synthetic-existing-passphrase"])
def test_missing_primary_never_creates_unrelated_material_for_existing_database(
    tmp_path: Path, passphrase: str | None
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock(passphrase)
        store.set("secret", "synthetic-value")
    before = _snapshot(tmp_path)
    primary = tmp_path / ("master.key" if passphrase is None else "master.salt")
    primary.unlink()  # Missing material in this synthetic fixture, not a live store.
    with SecureStore(base_dir=tmp_path) as rejected:
        with pytest.raises((InvalidToken, RuntimeError)):
            rejected.unlock(passphrase)
        assert not rejected.is_unlocked()
    assert _snapshot(tmp_path) == before
    assert not primary.exists(), (
        "rejected unlock must not publish an unrelated new key/salt"
    )


def test_malformed_primary_does_not_block_verified_pending_rotation_recovery(
    tmp_path: Path,
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock()
        store.set("secret", "synthetic-value")
        with patch.object(
            store,
            "_promote_pending_key_material",
            side_effect=OSError("synthetic pause"),
        ):
            with pytest.raises(OSError, match="synthetic pause"):
                store.rotate_master_key()
        store._master_key_path.write_bytes(b"malformed-key")
    pending = tmp_path / ".master.key.pending"
    check = dict(_snapshot(tmp_path)[0])["key_check"]
    assert isinstance(check, bytes)
    assert (
        Fernet(pending.read_bytes()).decrypt(check)
        == b"gunz-utils-secure-store-v2:strict"
    )
    with SecureStore(base_dir=tmp_path) as recovered:
        recovered.unlock()
        assert recovered.verify_integrity()
        assert recovered.get("secret") == "synthetic-value"
        assert not pending.exists()


def test_unsigned_generation_reset_cannot_authorize_obsolete_key_new_writes(
    tmp_path: Path,
) -> None:
    with (
        SecureStore(base_dir=tmp_path) as current,
        SecureStore(base_dir=tmp_path) as stale,
    ):
        current.unlock("synthetic-old-passphrase")
        stale.unlock("synthetic-old-passphrase")
        current.rotate_master_key("synthetic-new-passphrase")
        marker = dict(_snapshot(tmp_path)[0])["key_check"]
        current._conn.execute(
            "UPDATE store_meta SET value=? WHERE key='key_generation'", (b"1",)
        )
        # Only this unsigned counter changes; the authenticated current marker
        # is neither forged nor replayed from an older snapshot.
        with pytest.raises((RuntimeError, InvalidToken)):
            stale.set("future", "synthetic-future-secret")
        assert dict(_snapshot(tmp_path)[0])["key_check"] == marker
        assert not current._conn.execute(
            "SELECT name FROM secrets WHERE name='future'"
        ).fetchone()
        assert current._conn.execute(
            "SELECT COUNT(*) FROM audit WHERE action='set' AND allowed=1 "
            "AND secret_name='future'"
        ).fetchone()[0] == 0


@pytest.mark.parametrize("passphrase", [None, "synthetic-audit-only-passphrase"])
def test_audit_history_alone_prevents_missing_material_regeneration(
    tmp_path: Path, passphrase: str | None
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock(passphrase)
        store.set("secret", "synthetic-value")
        store._conn.execute("DELETE FROM secrets")
        store._conn.execute("DELETE FROM store_meta")
        before = list(store._conn.execute("SELECT * FROM audit"))
        primary = tmp_path / ("master.key" if passphrase is None else "master.salt")
        primary.unlink()
        with pytest.raises(RuntimeError, match="key material is missing"):
            store.unlock(passphrase)
        assert not primary.exists()
        assert list(store._conn.execute("SELECT * FROM audit")) == before
        assert _snapshot(tmp_path) == ({}, [])


def test_malformed_primary_and_wrong_pending_preserve_material_on_rejection(
    tmp_path: Path,
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock()
        store.set("secret", "synthetic-value")
    primary = tmp_path / "master.key"
    pending = tmp_path / ".master.key.pending"
    primary.write_bytes(b"malformed-key")
    pending.write_bytes(Fernet.generate_key())
    before = _snapshot(tmp_path)
    material = (primary.read_bytes(), pending.read_bytes())
    with SecureStore(base_dir=tmp_path) as rejected:
        with pytest.raises(InvalidToken):
            rejected.unlock()
        assert not rejected.is_unlocked()
    assert _snapshot(tmp_path) == before
    assert (primary.read_bytes(), pending.read_bytes()) == material


def test_unsafe_primary_read_is_not_skipped_for_valid_pending(tmp_path: Path) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock()
    primary = tmp_path / "master.key"
    pending = tmp_path / ".master.key.pending"
    material = primary.read_bytes()
    pending.write_bytes(material)
    target = tmp_path / "synthetic-key-target"
    primary.rename(target)
    primary.symlink_to(target)
    with SecureStore(base_dir=tmp_path) as rejected:
        with pytest.raises(ValueError, match="symlink"):
            rejected.unlock()
        assert not rejected.is_unlocked()
    assert primary.is_symlink()
    assert target.read_bytes() == pending.read_bytes() == material


@pytest.mark.parametrize("joined_transaction", [False, True])
def test_policy_guard_and_encryption_share_sqlite_write_exclusion(
    tmp_path: Path, joined_transaction: bool
) -> None:
    with (
        SecureStore(base_dir=tmp_path) as store,
        closing(sqlite3.connect(tmp_path / "config.db", timeout=0)) as raw_writer,
    ):
        store.unlock()
        marker = _snapshot(tmp_path)[0]["key_check"]
        verify = store._verify_key_generation
        attempts = []

        def verify_with_raw_writer_interleaving() -> None:
            verify()
            # Attempt an uncooperative writer exactly after authentication and
            # before the new-name encryption. No cooperative file lock is used.
            with pytest.raises(sqlite3.OperationalError, match="locked"):
                raw_writer.execute(
                    "UPDATE store_meta SET value=? WHERE key='key_check'",
                    (b"synthetic-corrupted-policy",),
                )
            raw_writer.rollback()
            attempts.append(True)

        if joined_transaction:
            store._conn.execute("BEGIN IMMEDIATE")
        with patch.object(
            store, "_verify_key_generation", verify_with_raw_writer_interleaving
        ):
            store.set("future", "synthetic-future-value")
        if joined_transaction:
            assert store._conn.in_transaction
            store._conn.execute("COMMIT")
        assert attempts == [True]
        assert _snapshot(tmp_path)[0]["key_check"] == marker
        assert store.get("future") == "synthetic-future-value"
