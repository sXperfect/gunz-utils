def test_malformed_primary_and_wrong_pending_preserve_material_on_rejection(
    tmp_path: Path,
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock()
        store.set("secret", "synthetic-value")
    primary = tmp_path / "master.key"
    pending = tmp_path / ".master.key.pending"
    primary.write_bytes(b"malformed-key")
    pending.write_bytes(Fernet.generate_key())
    before = _snapshot(tmp_path)
    material = (primary.read_bytes(), pending.read_bytes())
    with SecureStore(base_dir=tmp_path) as rejected:
        with pytest.raises(InvalidToken):
            rejected.unlock()
        assert not rejected.is_unlocked()
    assert _snapshot(tmp_path) == before
    assert (primary.read_bytes(), pending.read_bytes()) == material


def test_unsafe_primary_read_is_not_skipped_for_valid_pending(
    tmp_path: Path,
) -> None:
    with SecureStore(base_dir=tmp_path) as store:
        store.unlock()
    primary = tmp_path / "master.key"
    pending = tmp_path / ".master.key.pending"
    material = primary.read_bytes()
    pending.write_bytes(material)
    target = tmp_path / "synthetic-key-target"
    primary.rename(target)
    primary.symlink_to(target)
    with SecureStore(base_dir=tmp_path) as rejected:
        with pytest.raises(ValueError, match="symlink"):
            rejected.unlock()
        assert not rejected.is_unlocked()
    assert primary.is_symlink()
    assert target.read_bytes() == pending.read_bytes() == material


@pytest.mark.parametrize("joined_transaction", [False, True])
def test_policy_guard_and_encryption_share_sqlite_write_exclusion(
    tmp_path: Path,
    joined_transaction: bool,
) -> None:
    with (
        SecureStore(base_dir=tmp_path) as store,
        closing(sqlite3.connect(tmp_path / "config.db", timeout=0)) as raw_writer,
    ):
        store.unlock()
        marker = _snapshot(tmp_path)[0]["key_check"]
        verify = store._verify_key_generation
        attempts = []

        def verify_with_raw_writer_interleaving() -> None:
            verify()
            #? Attempt an uncooperative writer exactly after authentication and
            #? before the new-name encryption. No cooperative file lock is used.
            with pytest.raises(sqlite3.OperationalError, match="locked"):
                raw_writer.execute(
                    "UPDATE store_meta SET value=? WHERE key='key_check'",
                    (b"synthetic-corrupted-policy",),
                )
            raw_writer.rollback()
            attempts.append(True)

        if joined_transaction:
            store._conn.execute("BEGIN IMMEDIATE")
        with patch.object(
            store, "_verify_key_generation", verify_with_raw_writer_interleaving
        ):
            store.set("future", "synthetic-future-value")
        if joined_transaction:
            assert store._conn.in_transaction
            store._conn.execute("COMMIT")
        assert attempts == [True]
        assert _snapshot(tmp_path)[0]["key_check"] == marker
        assert store.get("future") == "synthetic-future-value"


